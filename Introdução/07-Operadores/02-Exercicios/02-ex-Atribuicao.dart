// Demonstrar os operadores de atribuição composto do Dart.

void main() {
  // Valor inicial que será modificado pelos operadores de atribuição.
  int x = 10;

  // Começo
  print("Valor inicial do x: $x");

  // Operadores de atribuição composto de adição.
  x += 3; // x = x + 3

  print("x += 3: $x");

  // ===========================================

  // Operadores de subtração composto.
  x -= 2; // x = x - 2

  print("x -= 2: $x");

  // ===========================================

  // Operadores de multiplicação sendo atribuido.
  x *= 4; // x = x * 4

  print("x *= 4: $x");
}
