// Operadores Relacionais de Comparação

void main() {

  // Dois valores para serem comparados entre si
  final int valor1 = 10;
  final int valor2 = 2;

  /*
  == (verifica a igualdade)
  != (verifica a diferença ou desigualdade)
  > (verifica quem é maior)
  < (verifica quem é menor)
  */
  print("$valor1 é igual a $valor2? ${valor1 == valor2}"); // false
  print("$valor1 é diferente de $valor2? ${valor1 != valor2}"); // true
  print("$valor1 é maior que $valor2? ${valor1 > valor2}"); // true
  print("$valor1 é menor que $valor2? ${valor1 < valor2}"); // false
}
