// Exercício que cria um programa que demonstra cinco operadores

void main() {
  
  // Declarando as variáveis numéricas
  final int a = 10; // variável "a"
  final int b = 5; // variável "b"

  print("Soma: ${a + b}"); // Operador adição ou somar.
  print("Subtração: ${a - b}"); // Operador de subtração.
  print("Multiplicação: ${a * b}"); // Operador de multiplicar.
  print("Divisão: ${a / b}"); // Operador de divisão.
  print("Resto da divisão: ${a % b}"); // Operador de resto de divisão.
}
