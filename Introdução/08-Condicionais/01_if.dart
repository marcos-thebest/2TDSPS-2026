// Exercício - classificação Numérica

void main() {

  var numero = -1; // Definindo o valor do número a ser verificado

  if (numero > 0) {
    // Verifica se o número é maior que zero...
    print("O número é positivo!"); // se verdadeiro - imprime essa mensagem
  } else if (numero < 0) {
    // Caso contrário, verifica se o número é menor que zero...
    print("O número é negativo!");
  } else {
    // Se nenhuma das condições anteriores for verdadeira, imprime essa mensagem
    print("O número é zero!");
  }
}
